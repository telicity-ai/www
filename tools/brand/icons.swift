// Rebuild favicons and home-screen icons from the approved C1 symbol.
// Requires macOS AppKit. Run from the repository root: swift tools/brand/icons.swift
import AppKit
import Foundation
import ImageIO

let root = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
let symbolURL = root.appendingPathComponent("assets/telicity/logos/logo-petrol.svg")
let symbol = try String(contentsOf: symbolURL, encoding: .utf8)
let iconDirectory = root.appendingPathComponent("assets/telicity/icons", isDirectory: true)
try FileManager.default.createDirectory(at: iconDirectory, withIntermediateDirectories: true)
let versionComment = "<!-- Generated by tools/brand/icons.swift from the approved C1 symbol. -->\n"
let light = symbol.replacingOccurrences(of: "  <title>", with: "  " + versionComment + "  <title>")
let dark = light.replacingOccurrences(of: "fill=\"#193E45\"", with: "fill=\"#F5F4EE\"")
let adaptive = light.replacingOccurrences(of: "  <g fill=\"#193E45\">", with: """
  <style>
    .mark { fill: #193E45; }
    @media (prefers-color-scheme: dark) {
      .mark { fill: #F5F4EE; }
    }
  </style>
  <g class="mark" fill="#193E45">
""")
try light.write(to: iconDirectory.appendingPathComponent("favicon-light.svg"), atomically: true, encoding: .utf8)
try dark.write(to: iconDirectory.appendingPathComponent("favicon-dark.svg"), atomically: true, encoding: .utf8)
try adaptive.write(to: root.appendingPathComponent("icon.svg"), atomically: true, encoding: .utf8)
guard let image = NSImage(contentsOf: symbolURL), let colorSpace = CGColorSpace(name: CGColorSpace.sRGB) else {
    fputs("Could not load the approved C1 symbol.\n", stderr)
    exit(1)
}

func png(size: Int) -> Data {
    guard let context = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8,
                                  bytesPerRow: size * 4, space: colorSpace,
                                  bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else {
        fatalError("Could not create the icon canvas")
    }
    // An opaque paper ground keeps raster fallbacks readable on any tab bar,
    // and prevents iOS from replacing transparent pixels with a black ground.
    context.setFillColor(red: 245.0 / 255, green: 244.0 / 255, blue: 238.0 / 255, alpha: 1)
    context.fill(CGRect(x: 0, y: 0, width: size, height: size))
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: false)
    NSGraphicsContext.current?.imageInterpolation = .high
    image.draw(in: NSRect(x: 0, y: 0, width: size, height: size), from: .zero, operation: .sourceOver, fraction: 1)
    NSGraphicsContext.restoreGraphicsState()
    guard let bitmap = context.makeImage() else { fatalError("Could not render icon") }
    let data = NSMutableData()
    guard let destination = CGImageDestinationCreateWithData(data, "public.png" as CFString, 1, nil) else {
        fatalError("Could not encode icon")
    }
    CGImageDestinationAddImage(destination, bitmap, nil)
    guard CGImageDestinationFinalize(destination) else { fatalError("Could not finish icon") }
    return data as Data
}
let rasterSizes = [16, 32, 48, 180, 192, 512]
let rasters = Dictionary(uniqueKeysWithValues: rasterSizes.map { ($0, png(size: $0)) })
for (size, filename) in [(32, "favicon-32x32.png"), (180, "apple-touch-icon.png"), (192, "icon-192.png"), (512, "icon-512.png")] {
    try rasters[size]!.write(to: root.appendingPathComponent(filename))
    print("\(filename): \(size)×\(size), \(rasters[size]!.count) bytes")
}

func uint16(_ value: Int) -> Data { Data([UInt8(value & 255), UInt8((value >> 8) & 255)]) }
func uint32(_ value: Int) -> Data { Data((0..<4).map { UInt8((value >> ($0 * 8)) & 255) }) }
let icoSizes = [16, 32, 48]
var header = uint16(0) + uint16(1) + uint16(icoSizes.count)
var payload = Data()
for size in icoSizes {
    let raster = rasters[size]!
    header += Data([UInt8(size), UInt8(size), 0, 0])
    header += uint16(1) + uint16(24) + uint32(raster.count) + uint32(6 + icoSizes.count * 16 + payload.count)
    payload += raster
}
try (header + payload).write(to: root.appendingPathComponent("favicon.ico"))
print("favicon.ico: \(icoSizes.map(String.init).joined(separator: "/")) px, \(header.count + payload.count) bytes")
print("icon.svg: petrol in light mode, paper in dark mode; static theme SVGs also generated")
